"""US-listed stocks and ETFs from Nasdaq Trader's symbol directory, for the header search.

Two pipe-delimited files, regenerated by Nasdaq every business day (free, no key):
  nasdaqlisted.txt   everything listed on Nasdaq
  otherlisted.txt    everything listed on NYSE, NYSE American, NYSE Arca, Cboe BZX, IEX, ...
The list is loaded once a day per worker process and searched in memory.

Kept: common shares, ETFs and share classes ("BRK.B"). Left out: test issues and preferred shares
("ABR$D"), whose symbols Yahoo writes differently. Symbols are returned in Yahoo's form
("BRK-B"), because the stock overview reads Yahoo.

Idea adapted from github.com/Jakeschincariol/day-trader-skill (MIT).
"""
from __future__ import annotations

import logging
import re
import threading
import time

import requests

logger = logging.getLogger(__name__)

URLS = ("https://www.nasdaqtrader.com/dynamic/SymDir/nasdaqlisted.txt",
        "https://www.nasdaqtrader.com/dynamic/SymDir/otherlisted.txt")
HTTP_TIMEOUT_S = 15
TTL_S = 24 * 3600
RETRY_S = 10 * 60          # after a failed download, wait this long before trying again
# Exchange codes in otherlisted.txt, as documented with the symbol directory. Others show as "Other".
EXCHANGES = {"A": "NYSE American", "N": "NYSE", "P": "NYSE Arca", "Z": "Cboe BZX", "V": "IEX"}
_KEEP = re.compile(r"^[A-Z]{1,6}(\.[A-Z]{1,2})?$")
# Boilerplate at the end of Nasdaq's security names: "Apple Inc. - Common Stock" -> "Apple Inc."
_NAME_TAIL = re.compile(r"\s*[-–]?\s*(Common Stock|Common Shares|Ordinary Shares|Class [A-Z] Common Stock)\b.*$",
                        re.IGNORECASE)

_lock = threading.Lock()
_rows: list[dict] = []
_by_symbol: dict[str, dict] = {}
_loaded_at = 0.0
_failed_at = 0.0


def _clean_name(name: str) -> str:
    short = _NAME_TAIL.sub("", name).strip(" -,")
    return short or name.strip()


def parse(nasdaq_text: str, other_text: str) -> list[dict]:
    """Both files -> [{symbol (Yahoo form), name, exchange, etf}], sorted by symbol."""
    out = {}
    for text, listed in ((nasdaq_text, "nasdaq"), (other_text, "other")):
        lines = [ln for ln in text.splitlines() if ln.strip()]
        if not lines:
            continue
        header = lines[0].split("|")
        for line in lines[1:]:
            if line.startswith("File Creation Time"):
                continue
            r = dict(zip(header, line.split("|")))
            sym = r.get("Symbol") if listed == "nasdaq" else r.get("ACT Symbol")
            if not sym or r.get("Test Issue") == "Y" or not _KEEP.match(sym):
                continue
            exchange = "Nasdaq" if listed == "nasdaq" else EXCHANGES.get(r.get("Exchange", ""), "Other")
            yahoo = sym.replace(".", "-")
            # Main board: Nasdaq Global Select (category Q) or the NYSE itself, the two tiers with the
            # strictest size requirements. The files carry no market cap, so this is the only size hint;
            # search uses it to put Microsoft ahead of MicroAlgo.
            main = r.get("Market Category") == "Q" if listed == "nasdaq" else r.get("Exchange") == "N"
            out[yahoo] = {"symbol": yahoo, "name": _clean_name(r.get("Security Name", "")),
                          "exchange": exchange, "etf": r.get("ETF") == "Y", "main_board": main}
    return sorted(out.values(), key=lambda x: x["symbol"])


def _load() -> list[dict]:
    """The cached list, refreshed once a day; an empty list while Nasdaq has never been reachable."""
    global _rows, _by_symbol, _loaded_at, _failed_at
    with _lock:
        now = time.monotonic()
        if _rows and now - _loaded_at < TTL_S:
            return _rows
        if _failed_at and now - _failed_at < RETRY_S:
            return _rows
        try:
            texts = []
            for url in URLS:
                resp = requests.get(url, timeout=HTTP_TIMEOUT_S)
                resp.raise_for_status()
                texts.append(resp.text)
            rows = parse(*texts)
            if len(rows) < 1000:  # a truncated or changed file: keep what we had
                raise ValueError(f"only {len(rows)} symbols parsed")
        except (requests.RequestException, ValueError) as exc:
            logger.warning("nasdaq symbol directory failed err=%s", exc)
            _failed_at = now
            return _rows
        _rows, _by_symbol, _loaded_at, _failed_at = rows, {r["symbol"]: r for r in rows}, now, 0.0
        logger.info("nasdaq symbol directory loaded symbols=%d", len(rows))
        return _rows


def available() -> bool:
    return bool(_load())


def get(symbol: str) -> dict | None:
    """The listing for an exact symbol, in either form ("BRK.B" or "BRK-B")."""
    _load()
    return _by_symbol.get(symbol.strip().upper().replace(".", "-"))


def search(query: str, limit: int = 8) -> list[dict]:
    """Best matches for what the user typed: the exact symbol, then symbols starting with it
    (shortest base symbol first, so BRK-B comes before BRKC), then names starting with it, names with
    a word starting with it, and names containing it. Among name matches, stocks come before ETFs
    and main-board listings before the rest."""
    q = query.strip().upper()
    rows = _load()
    if not q or not rows:
        return []
    qs = q.replace(".", "-")
    words = re.compile(r"\b" + re.escape(q), re.IGNORECASE)

    def rank(r):
        s, name = r["symbol"], r["name"].upper()
        if s == qs:
            return (0, 0, 0, s)
        if s.startswith(qs):
            return (1, len(s.split("-")[0]), len(s), s)
        tier = 2 if name.startswith(q) else 3 if words.search(name) else 4 if q in name else None
        if tier is None:
            return None
        return (tier, (r["etf"], not r.get("main_board", False)), len(name), s)

    ranked = sorted((k, r) for r in rows if (k := rank(r)) is not None)
    return [r for _, r in ranked[:limit]]
